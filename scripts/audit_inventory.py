"""Inventory structure audit. Writes verification/coverage-report.md (GENERATED). Usage: python scripts/audit_inventory.py

Heuristic checks for a reviewer to look at, not verdicts: duplicate candidates, breadth, fragmentation, missing prerequisites,
isolated concepts and cross-domain dependencies. Source coverage (official docs, roles, production, interviews) is recorded
in verification/inventory-audit.yaml, not here.
"""
import re
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
STOP = {"and", "the", "of", "in", "for", "to", "a", "an", "with", "vs", "on", "basics", "overview", "fundamentals"}


def toks(s):
    return {w for w in re.findall(r"[a-z0-9_]+", s.lower()) if w not in STOP and len(w) > 1}


def jaccard(a, b):
    return len(a & b) / len(a | b) if a | b else 0.0


def main():
    inv = yaml.safe_load((ROOT / "master-index.yaml").read_text(encoding="utf-8"))["nodes"]
    nodes = {n["id"]: n for n in inv}
    concepts = [n for n in inv if n["level"] == "concept"]
    dom = lambda n: n["id"].split("-")[0]
    codes = [n["id"] for n in inv if n["level"] == "domain"]
    pri = ["P0", "P1", "P2", "P3"]
    out = ["# Inventory structure report", "",
           "GENERATED by `scripts/audit_inventory.py` from `master-index.yaml`. These are review prompts, not verdicts. "
           "Source coverage is recorded separately in `verification/inventory-audit.yaml`.", "",
           "## Concepts by domain and priority", "", "| Domain | P0 | P1 | P2 | P3 | Total | Topics |", "|---|---|---|---|---|---|---|"]
    cnt = Counter((dom(n), n["priority"]) for n in concepts)
    topics = Counter(dom(n) for n in inv if n["level"] == "topic")
    for c in codes:
        row = [cnt[(c, p)] for p in pri]
        out.append(f"| {c} {nodes[c]['title']} | " + " | ".join(map(str, row)) + f" | {sum(row)} | {topics[c]} |")
    tot = [sum(cnt[(c, p)] for c in codes) for p in pri]
    out.append(f"| **Total** | " + " | ".join(f"**{x}**" for x in tot) + f" | **{sum(tot)}** | **{sum(topics.values())}** |")
    comp = Counter((n["competency"]) for n in concepts)
    out += ["", "Expected competency across concepts: " + ", ".join(f"{k} {v}" for k, v in sorted(comp.items())), ""]
    srcs = Counter(n["source_category"] for n in concepts)
    out += ["Planned source category: " + ", ".join(f"{k} {v}" for k, v in sorted(srcs.items())), ""]

    out += ["## Duplicate candidates (title or scope token overlap >= 0.6, different concepts)", ""]
    pairs = []
    for i, a in enumerate(concepts):
        for b in concepts[i + 1:]:
            s = max(jaccard(toks(a["title"]), toks(b["title"])), jaccard(toks(a["scope"]), toks(b["scope"])))
            if s >= 0.6:
                pairs.append((s, a, b))
    for s, a, b in sorted(pairs, key=lambda x: -x[0]):
        out.append(f"- {s:.2f}: **{a['id']}** {a['title']} <-> **{b['id']}** {b['title']}")
    if not pairs:
        out.append("- none")

    out += ["", "## Possibly broad concepts (scope lists >= 6 comma-separated items or title lists >= 3 items)", ""]
    broad = [n for n in concepts if n["scope"].count(",") >= 5 or len(re.split(r",| and ", n["title"])) >= 4]
    out += [f"- **{n['id']}** {n['title']} ({n['scope'].count(',') + 1} scope items)" for n in broad] or ["- none"]

    out += ["", "## Topic sizes (concepts per topic; small topics may be fragmentation, large ones may need subtopics)", ""]
    size = Counter()
    for n in concepts:
        p = nodes[n["parent"]]
        size[p["parent"] if p["level"] == "subtopic" else p["id"]] += 1
    small = sorted(((v, k) for k, v in size.items() if v <= 4))
    large = sorted(((v, k) for k, v in size.items() if v >= 16), reverse=True)
    out += [f"- small: {k} {nodes[k]['title']} ({v})" for v, k in small] or ["- no topic has 4 or fewer concepts"]
    out += [f"- large: {k} {nodes[k]['title']} ({v})" for v, k in large] or ["- no topic has 16 or more concepts"]

    refs = defaultdict(int)
    for n in concepts:
        for r in n["prereqs"] + n["related"]:
            refs[r] += 1
    noprereq = [n for n in concepts if not n["prereqs"]]
    out += ["", "## Concepts with no prerequisites (expected for entry points; review the rest)", "",
            "Entry points are fine at P0. Listed here: P1 and above with none, which may indicate a missing prerequisite.", ""]
    out += [f"- **{n['id']}** {n['title']} ({n['priority']})" for n in noprereq if n["priority"] != "P0"] or ["- none"]
    iso = [n for n in concepts if not n["prereqs"] and refs[n["id"]] == 0]
    out += ["", "## Isolated concepts (no prerequisites, never referenced by another concept)", ""]
    out += [f"- **{n['id']}** {n['title']} ({n['priority']})" for n in iso] or ["- none"]
    leaf = [n for n in concepts if refs[n["id"]] == 0 and n["priority"] in {"P0", "P1"}]
    out += ["", f"{len(leaf)} P0/P1 concepts are not referenced by any other concept (leaves; normal for applied topics).", ""]

    edges = Counter()
    for n in concepts:
        for r in n["prereqs"]:
            if dom(nodes[r]) != dom(n):
                edges[(dom(n), dom(nodes[r]))] += 1
    out += ["## Cross-domain prerequisite edges (dependent -> prerequisite domain)", "", "| From | To | Edges |", "|---|---|---|"]
    out += [f"| {a} | {b} | {c} |" for (a, b), c in sorted(edges.items(), key=lambda x: -x[1])]
    rv = [n for n in concepts if n.get("review_cycle")]
    out += ["## Material flagged for periodic review (review_cycle)", "",
            f"{len(rv)} concepts: " + ", ".join(f"{c} {sum(1 for n in rv if n['review_cycle'] == c)}" for c in ("quarterly", "semiannual")), ""]
    out += [f"- **{n['id']}** {n['title']} ({n['review_cycle']})" for n in rv]
    tg = Counter(dom(n) for n in concepts if "interview" in (n.get("tags") or []))
    out += ["", "## Interview-tagged concepts by domain (cross-index: INTERVIEW_INDEX.md)", "",
            ", ".join(f"{c} {tg[c]}" for c in codes) + f"; total {sum(tg.values())}", ""]
    p0 = [n for n in concepts if n["priority"] == "P0"]
    out += ["", f"## P0 closure check", "",
            f"{len(p0)} P0 concepts; every prerequisite of a P0 concept is itself P0 (enforced by the validator's priority-inversion rule)."]
    (ROOT / "verification" / "coverage-report.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("wrote verification/coverage-report.md;", len(concepts), "concepts,", len(pairs), "duplicate candidates,", len(broad), "possibly broad")


if __name__ == "__main__":
    main()
