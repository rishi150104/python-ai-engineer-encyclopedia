"""Generate the independent-review package for one entry.

Usage: python scripts/make_review_checklist.py PY-0002

Writes verification/review/<ID>.checklist.md (GENERATED, safe to regenerate, read-only for the reviewer) and creates
verification/review/<ID>.reviewer.yaml ONLY if absent, otherwise appends blocks for new claims. The reviewer file is the
reviewer's own input and is never rewritten or reordered by this script.
"""
import gzip
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import check_claims as cc  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
RANK = {"critical": 0, "important": 1, "minor": 2}


def page_text(sid):
    snap = ROOT / "verification" / "snapshots" / f"{sid}.html.gz"
    return cc.to_text(gzip.decompress(snap.read_bytes())) if snap.exists() else ""


def excerpt(text, quote, width=300):
    nq = cc.norm(quote)
    i = text.find(nq)
    if i < 0:
        return f"[quote NOT FOUND in snapshot: {nq}]"
    return f"...{text[max(0, i - width):i]}⟦{nq}⟧{text[i + len(nq):i + len(nq) + width]}..."


def reviewer_block(c):
    return (f"  {c['id']}:  # {c['importance']} | {c['support']} | {c['text'][:90].replace(chr(10), ' ')}\n"
            "    verdict: PENDING            # AGREE | DISAGREE | UNABLE_TO_JUDGE\n"
            '    comment: ""                 # required for DISAGREE / UNABLE_TO_JUDGE; optional otherwise\n'
            '    corrected_wording: ""       # optional: the wording you believe the source supports\n'
            '    resolution: ""              # AUTHOR fills after a DISAGREE: RESOLVED_CORRECTED | RESOLVED_REJECTED\n'
            '    resolution_note: ""\n'
            "    reviewer_accepts_resolution: null   # reviewer sets true/false after reading the resolution\n")


def main(eid):
    rec = yaml.safe_load((ROOT / "verification" / f"{eid}.yaml").read_text(encoding="utf-8"))
    reg = {s["id"]: s for s in yaml.safe_load((ROOT / "source-registry.yaml").read_text(encoding="utf-8"))["sources"]}
    gen = yaml.safe_load((ROOT / "verification" / "generated" / "sources.yaml").read_text(encoding="utf-8"))["sources"]
    res = yaml.safe_load((ROOT / "verification" / "generated" / f"{eid}.results.yaml").read_text(encoding="utf-8"))
    examples = {e["id"]: e for e in rec.get("examples") or []}
    claims = sorted((c for c in rec["claims"] if c.get("source")), key=lambda c: (RANK[c["importance"]], int(c["id"][1:])))
    out = [f"# Independent review checklist: {eid}", "",
           "GENERATED by `scripts/make_review_checklist.py` from the claim record and the stored source snapshots. Regenerating is safe;",
           f"record your answers in **`verification/review/{eid}.reviewer.yaml`**, not in this file.", "",
           "## What you are being asked", "",
           "For each claim: **does the quoted source text, as it appears in the source, establish the claim exactly as worded, and no more?**",
           "The mechanical checks already show the quotes are present in the page. They do not show the quotes support the claim.", "",
           "Look for:", "",
           "- dropped qualifiers (\"typically\", \"when possible\", \"CPython implementation detail\", \"may or may not\");",
           "- the claim being broader than the quote (an extra case, an extra type, a guarantee where the source gives a motivation);",
           "- a conclusion that needs a premise from another passage (inferred claims must be confirmed by the named example);",
           "- version dependence (the claim is stated for 3.11; the 3.13 text is shown when its wording differs);",
           "- a quote that is true but about something adjacent.", "",
           "## How to answer", "",
           f"1. Open `verification/review/{eid}.reviewer.yaml`. Fill `reviewer` (name, kind `human` or `other_model`, date, and `independent_of_author: true` "
           "only if you did not write or draft this page).",
           "2. For every claim set `verdict` to `AGREE`, `DISAGREE` or `UNABLE_TO_JUDGE`. Add a `comment` for anything but a plain AGREE, and "
           "`corrected_wording` if you can say what the source does support.",
           "3. Form your verdict from the **source excerpt first**. The author's judgment is in a collapsed block under each claim; read it afterwards "
           "so it does not anchor you.",
           "4. After a DISAGREE the author records a `resolution`; then you set `reviewer_accepts_resolution`.",
           "5. When every claim is AGREE (or a resolved DISAGREE you accepted), set `independent_review.status: DONE` in "
           f"`verification/{eid}.yaml` and run `python scripts/validate.py`. The validator checks coverage and that you are recorded as independent.", "",
           "Also glance at the page itself (`entries/py/PY-0002.md`): tags `[Cn]` documented / `E1`.. observed / `[J]` judgment. Report anywhere a `[J]` "
           "statement reads like a language rule, or an untagged sentence makes a factual claim. Put these in `page_comments` in the reviewer file.", ""]
    sens = [c for c in claims if c.get("version_note")]
    out += ["## Version-sensitive claims (read these first)", "",
            "| Claim | Applies to | Note |", "|---|---|---|"]
    for c in sens:
        out.append(f"| [{c['id']}](#{c['id'].lower()}) | {', '.join(v for v, r in res['claims'][c['id']]['versions'].items() if r == 'PASS')} (quote evidence) | {c['version_note']} |")
    out += ["", "**C25 and the pre-3.11 limitation:** the page says the general \"unhashable default\" check applies from Python 3.11 and that earlier "
            "versions rejected only `list`, `dict` and `set`. The only evidence for the *earlier* behaviour is the 3.11 documentation's own "
            "\"Changed in version 3.11\" sentence. The 3.10 documentation was **not** compared. If you can, check "
            "https://docs.python.org/3.10/library/dataclasses.html (and the 3.10 behaviour of `@dataclass` with a `tuple`-containing-list default) "
            "and say whether the page's pre-3.11 statement is acceptable as worded.", "",
            "## Summary", "", "| Claim | Importance | Support | Source section | 3.11 | 3.13 |", "|---|---|---|---|---|---|"]
    for c in claims:
        v = res["claims"][c["id"]]["versions"]
        out.append(f"| [{c['id']}](#{c['id'].lower()}) | {c['importance']} | {c['support']} | {c['section']} | {v['3.11']} | {v['3.13']} |")
    out += ["", f"{len(claims)} sourced claims. The unsourced judgment claim (C30) and `[J]` text are not part of this checklist.", ""]
    for c in claims:
        sid = c["source"]
        out += [f"## {c['id']}", "",
                f"- **Importance / support:** {c['importance']} / {c['support']}",
                f"- **Claim as worded:** {c['text']}",
                f"- **Source:** {reg[sid]['title']} ({sid}), section *{c['section']}*",
                f"- **URL:** {reg[sid]['url']}  ·  snapshot `{gen[sid]['snapshot']}` (sha256 `{gen[sid]['sha256'][:16]}…`, documentation {gen[sid]['doc_version']}, accessed {gen[sid]['accessed_on']})",
                f"- **Mechanical result:** quotes present in 3.11 = {res['claims'][c['id']]['versions']['3.11']}, 3.13 = {res['claims'][c['id']]['versions']['3.13']}"]
        if c.get("version_note"):
            out.append(f"- **Version note:** {c['version_note']}")
        if c.get("reviewer_note"):
            out.append(f"- **Note to reviewer:** {c['reviewer_note']}")
        if c.get("verified_by"):
            for x in c["verified_by"]:
                ex = examples[x]
                out.append(f"- **Inference confirmed by example {x}** (`{ex['file']}`); expected output:")
                out += ["", "  ```text"] + [f"  {ln}" for ln in str(ex["expected_output"]).splitlines()] + ["  ```"]
        out += ["", "**Supporting excerpts, Python 3.11 documentation** (the ⟦ ⟧ marks the exact quote the claim relies on):", ""]
        t311 = page_text(sid)
        for q in c["quotes"]:
            out += ["```text", excerpt(t311, q), "```", ""]
        alt = (c.get("quotes_by_version") or {}).get("3.13")
        if alt:
            sid13 = sid.replace("-3.11", "-3.13")
            out += ["**Python 3.13 documentation uses different wording for this claim:**", ""]
            t313 = page_text(sid13)
            for q in alt:
                out += ["```text", excerpt(t313, q), "```", ""]
        rv = c.get("review")
        if rv:
            out += ["<details><summary>Author's judgment (read after forming your own verdict)</summary>", "",
                    f"Entailment: **{rv['entailment']}** by {rv['reviewer']} on {rv['date']}.", "", rv["note"], "", "</details>", ""]
        out += [f"Your answer: `verification/review/{eid}.reviewer.yaml` → `claims.{c['id']}`", ""]
    review_dir = ROOT / "verification" / "review"
    review_dir.mkdir(parents=True, exist_ok=True)
    (review_dir / f"{eid}.checklist.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    rpath = review_dir / f"{eid}.reviewer.yaml"
    if not rpath.exists():
        head = (f"# Reviewer input for {eid}. HUMAN-OWNED: scripts create this once and only ever append blocks for new claims.\n"
                f"# Instructions: verification/review/{eid}.checklist.md\n"
                "reviewer:\n  name: null\n  kind: null                  # human | other_model\n  date: null\n"
                "  independent_of_author: null  # true only if you did not write or draft the page\n"
                '  affiliation_note: ""\n'
                'page_comments: []               # list of strings: [J]/untagged statements that read like language rules, wording problems, etc.\n'
                "claims:\n")
        rpath.write_text(head + "".join(reviewer_block(c) for c in claims), encoding="utf-8", newline="\n")
        print("created", rpath.relative_to(ROOT))
    else:
        existing = yaml.safe_load(rpath.read_text(encoding="utf-8"))["claims"]
        new = [c for c in claims if c["id"] not in existing]
        if new:
            with rpath.open("a", encoding="utf-8", newline="\n") as f:
                f.write("".join(reviewer_block(c) for c in new))
        print("kept", rpath.relative_to(ROOT), f"(+{len(new)} new claim blocks)")
    print("wrote", (review_dir / f"{eid}.checklist.md").relative_to(ROOT), f"({len(claims)} claims)")


if __name__ == "__main__":
    main(sys.argv[1])
