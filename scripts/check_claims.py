"""Check that every claim's verbatim `quotes` appear in the cited sources, per documentation version.

Usage: python scripts/check_claims.py PY-0002 [--refresh]

Sources are read from gzipped snapshots (verification/snapshots/), so the check is reproducible offline.
--refresh re-fetches live pages and replaces the snapshots. A claim is also checked against the same page of
Python 3.13 when a source with id ...-3.13 is registered, using `quotes_by_version: {"3.13": [...]}` when the
wording differs. Only quote PRESENCE is checked here; whether a quote entails the claim is the human-authored
`review` field in the record.

Writes only machine-owned files, never the human-authored record or registry:
  verification/generated/sources.yaml, <ID>.results.yaml, <ID>.excerpts.md
"""
import datetime
import gzip
import hashlib
import html
import re
import sys
import urllib.request
from html.parser import HTMLParser
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GEN = "verification/generated"
BLOCK = {"p", "li", "div", "pre", "br", "dt", "dd", "tr", "td", "th", "h1", "h2", "h3", "h4", "h5", "h6", "section"}
VERSIONS = {"3.11": "-3.11", "3.13": "-3.13"}


class Text(HTMLParser):
    def __init__(self):
        super().__init__()
        self.out, self.skip = [], 0

    def handle_starttag(self, tag, attrs):
        self.skip += tag in ("script", "style")
        if tag in BLOCK:  # inline tags (code, span) must not add whitespace inside a quoted phrase
            self.out.append(" ")

    def handle_endtag(self, tag):
        self.skip -= tag in ("script", "style")

    def handle_data(self, data):
        if not self.skip:
            self.out.append(data)


def norm(s):
    s = html.unescape(s).replace("¶", "")
    for a, b in (("’", "'"), ("‘", "'"), ("“", '"'), ("”", '"'), ("—", "-")):
        s = s.replace(a, b)
    return re.sub(r"\s+", " ", s).strip()


def to_text(raw):
    p = Text()
    p.feed(raw.decode("utf-8"))
    return norm("".join(p.out))


def evaluate(claims, texts, registered):
    """Pure: {claim id: {check, versions}} from {source id: normalised page text}. `registered` = known source ids."""
    out = {}
    for c in claims:
        if not c.get("source"):
            continue
        versions = {}
        for ver, suffix in VERSIONS.items():
            sid = c["source"].replace("-3.11", suffix)
            if sid not in registered or sid not in texts:
                versions[ver] = "NOT_CHECKED"
                continue
            quotes = (c.get("quotes_by_version") or {}).get(ver, c.get("quotes"))
            ok = bool(quotes) and all(norm(q) in texts[sid] for q in quotes)
            versions[ver] = "PASS" if ok else "FAIL"
        out[c["id"]] = {"check": versions["3.11"], "versions": versions}
    return out


def excerpts_md(eid, claims, texts):
    lines = [f"# Source excerpts for {eid}", "", "GENERATED by scripts/check_claims.py from the snapshots. Do not edit.", ""]
    for c in claims:
        if not c.get("source"):
            continue
        lines += [f"## {c['id']} ({c['source']})", ""]
        for q in c.get("quotes") or []:
            t, nq = texts.get(c["source"], ""), norm(q)
            i = t.find(nq)
            lines.append(f"> ...{t[max(0, i - 200):i + len(nq) + 200]}..." if i >= 0 else f"> NOT FOUND: {nq}")
            lines.append("")
    return "\n".join(lines) + "\n"


def dump_generated(path, data, note):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"# GENERATED by scripts/{note}. Do not edit by hand; human notes belong in the record/registry.\n"
                    + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8", newline="\n")


def main(eid, refresh=False):
    rec = yaml.safe_load((ROOT / "verification" / f"{eid}.yaml").read_text(encoding="utf-8"))
    registry = {s["id"]: s for s in yaml.safe_load((ROOT / "source-registry.yaml").read_text(encoding="utf-8"))["sources"]}
    gen_path = ROOT / GEN / "sources.yaml"
    gen = (yaml.safe_load(gen_path.read_text(encoding="utf-8")) if gen_path.exists() else None) or {}
    gsrc = gen.setdefault("sources", {})
    wanted = {c["source"].replace("-3.11", suf) for c in rec["claims"] if c.get("source") for suf in VERSIONS.values()}
    texts = {}
    for sid in sorted(wanted & registry.keys()):
        snap = ROOT / "verification" / "snapshots" / f"{sid}.html.gz"
        if refresh or not snap.exists():
            req = urllib.request.Request(registry[sid]["url"], headers={"User-Agent": "encyclopedia-claim-check"})
            raw = urllib.request.urlopen(req, timeout=60).read()
            snap.parent.mkdir(parents=True, exist_ok=True)
            snap.write_bytes(gzip.compress(raw, mtime=0))  # mtime=0: byte-identical snapshot for identical input
            ver = re.search(r"(3\.\d+\.\d+) Documentation", to_text(raw))
            gsrc[sid] = {"access_status": "FETCHED", "accessed_on": datetime.date.today().isoformat(), "retrieval": "raw",
                         "sha256": hashlib.sha256(raw).hexdigest(), "bytes": len(raw),
                         "doc_version": ver.group(1) if ver else None, "snapshot": snap.relative_to(ROOT).as_posix()}
        else:
            raw = gzip.decompress(snap.read_bytes())
            if hashlib.sha256(raw).hexdigest() != gsrc.get(sid, {}).get("sha256"):
                sys.exit(f"snapshot {snap} does not match the recorded sha256; run with --refresh")
        texts[sid] = to_text(raw)
    results = evaluate(rec["claims"], texts, registry.keys())
    today = datetime.date.today().isoformat()
    for r in results.values():
        r["checked_on"] = today
    prev = yaml.safe_load((ROOT / GEN / f"{eid}.results.yaml").read_text(encoding="utf-8")) if (ROOT / GEN / f"{eid}.results.yaml").exists() else {}
    prev = prev or {}
    dump_generated(gen_path, gen, "check_claims.py")
    dump_generated(ROOT / GEN / f"{eid}.results.yaml", {"id": eid, "claims": results, "examples": prev.get("examples", {})}, "check_claims.py and run_examples.py")
    (ROOT / GEN / f"{eid}.excerpts.md").write_text(excerpts_md(eid, rec["claims"], texts), encoding="utf-8", newline="\n")
    bad = {k: v for k, v in results.items() if "FAIL" in v["versions"].values()}
    for k, v in bad.items():
        print("FAIL", k, v["versions"])
    print(f"{len(results)} sourced claims; {len(bad)} with a FAIL; versions PASS: " +
          ", ".join(f"{ver}={sum(r['versions'][ver] == 'PASS' for r in results.values())}" for ver in VERSIONS))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main(sys.argv[1], "--refresh" in sys.argv)
