"""Run the executable examples of one entry and record results in verification/generated/<ID>.results.yaml.

Usage: python scripts/run_examples.py PY-0002 [--python PATH_TO_OTHER_INTERPRETER]

Without --python, results are the primary run (this interpreter) and decide PASSED/FAILED. With --python, the
observed result is added to `extra_runs`; it never changes the primary result. Stdout must equal expected_output.
The human-authored record (verification/<ID>.yaml) is never modified.
"""
import datetime
import importlib.metadata as md
import platform
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent


def run_one(exe, ex):
    # -I: isolated mode, so the script directory is not put on sys.path
    r = subprocess.run([exe, "-I", str(ROOT / ex["file"])], capture_output=True, text=True, timeout=60, encoding="utf-8")
    out = r.stdout.strip() if r.returncode == 0 else f"exit {r.returncode}\n{r.stderr.strip()}"
    ok = r.returncode == 0 and r.stdout.strip() == str(ex["expected_output"]).strip()
    return out, "PASSED" if ok else "FAILED"


def main(eid, other=None):
    rec = yaml.safe_load((ROOT / "verification" / f"{eid}.yaml").read_text(encoding="utf-8"))
    res_path = ROOT / "verification" / "generated" / f"{eid}.results.yaml"
    res = (yaml.safe_load(res_path.read_text(encoding="utf-8")) if res_path.exists() else None) or {"id": eid, "claims": {}}
    exres = res.setdefault("examples", {})
    today, failed = datetime.date.today().isoformat(), 0
    if other:
        pyver = subprocess.run([other, "-c", "import platform;print(platform.python_version())"], capture_output=True, text=True).stdout.strip()
    for ex in rec.get("examples") or []:
        if ex.get("not_executable_reason"):
            exres[ex["id"]] = {"execution": "NOT_EXECUTABLE", "reason": ex["not_executable_reason"]}
            continue
        if other:
            if ex.get("requires"):
                print(ex["id"], "skipped: needs third-party packages, dependencies unknown for", pyver)
                continue
            out, status = run_one(other, ex)
            runs = [r for r in exres.setdefault(ex["id"], {}).get("extra_runs", []) if r["python"] != pyver]
            runs.append({"python": pyver, "execution": status, "actual_output": out, "run_on": today})
            exres[ex["id"]]["extra_runs"] = runs
        else:
            out, status = run_one(sys.executable, ex)
            prev = exres.get(ex["id"], {})
            exres[ex["id"]] = {"execution": status, "actual_output": out,
                               "environment": {"python": platform.python_version(), "os": platform.platform()},
                               "dependencies": {p: md.version(p) for p in ex.get("requires") or []}, "run_on": today,
                               **({"extra_runs": prev["extra_runs"]} if prev.get("extra_runs") else {})}
        failed += status == "FAILED"
        print(ex["id"], status, f"(python {pyver})" if other else "")
    res_path.parent.mkdir(parents=True, exist_ok=True)
    res_path.write_text("# GENERATED by scripts/check_claims.py and run_examples.py. Do not edit by hand.\n"
                        + yaml.safe_dump(res, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8", newline="\n")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    a = sys.argv
    main(a[1], a[a.index("--python") + 1] if "--python" in a else None)
